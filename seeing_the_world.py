visit_list = ['saudi arabia', 'japan', 'china', 'italia', 'england']

# Original
print(visit_list)
# Sorted
print(sorted(visit_list))
# Original
print(visit_list)
# Sorted reversed
print(sorted(visit_list, reverse=True))
# Original
print(visit_list)
# Reversed
visit_list.reverse()
print(visit_list)
# Back to Original
visit_list.reverse()
print(visit_list)
# Sort in Alphabetical order
visit_list.sort()
print(visit_list)
# Sort in reverse-alphabetical order
visit_list.sort(reverse=True)
print(visit_list)